# Canonical digests for the 64 fixed states generated by the historical
# pre-control implementation.  They make a baseline drift visible even if an
# uncontrolled path is accidentally changed in lockstep with controlled L4.
HISTORICAL_UNCONTROLLED_STATE_DIGEST = "1a20d1aa7afadcb5f1d5d3b2ed556fe7033a89c17df03fffecd03a37ac74c1e8"
HISTORICAL_L4_WORLD_DIGEST = "d256b0c936c4e47b07459b2140d2c26691ef74c8a416a6659468eccdeadce8ab"


